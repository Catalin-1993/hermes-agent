// Brain: renders the menu-bar icon (a brain, lucide "brain", ISC) and its status badges to template PNGs and
// writes them as base64 into electron/hud-tray-icons.ts. Run: node scripts/gen-hud-tray-icons.mjs <playwright-core>
import fs from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'

const playwrightPath = process.argv[2] || 'playwright-core'
const { chromium } = await import(playwrightPath.startsWith('/') ? pathToFileURL(playwrightPath).href : playwrightPath)

const BRAIN = [
  'M12 5a3 3 0 1 0-5.997.125 4 4 0 0 0-2.526 5.77 4 4 0 0 0 .556 6.588A4 4 0 1 0 12 18Z',
  'M12 5a3 3 0 1 1 5.997.125 4 4 0 0 1 2.526 5.77 4 4 0 0 1-.556 6.588A4 4 0 1 1 12 18Z',
  'M15 13a4.5 4.5 0 0 1-3-4 4.5 4.5 0 0 1-3 4',
  'M17.599 6.5a3 3 0 0 0 .399-1.375',
  'M6.003 5.125A3 3 0 0 0 6.401 6.5',
  'M3.477 10.896a4 4 0 0 1 .585-.396',
  'M19.938 10.5a4 4 0 0 1 .585.396',
  'M6 18a4 4 0 0 1-1.967-.516',
  'M19.967 17.484A4 4 0 0 1 18 18'
]

// The badge sits top-right, cut out of the brain so it reads at 18px.
const badges = {
  idle: '',
  working1: '<circle cx="19.5" cy="4.5" r="1.4" fill="#000"/>',
  working2: '<circle cx="19.5" cy="4.5" r="2.2" fill="#000"/>',
  working3: '<circle cx="19.5" cy="4.5" r="3" fill="#000"/>',
  waiting: '<circle cx="19.5" cy="4.5" r="3.2" fill="#000"/>',
  done: '<path d="M17 4.6l1.7 1.7 3.1-3.3" fill="none" stroke="#000" stroke-width="1.9" stroke-linecap="round" stroke-linejoin="round"/>'
}

const svg = (badge, px) => `<svg xmlns="http://www.w3.org/2000/svg" width="${px}" height="${px}" viewBox="0 0 24 24">
  <defs><mask id="m"><rect width="24" height="24" fill="#fff"/>${badge ? '<circle cx="19.5" cy="4.5" r="5" fill="#000"/>' : ''}</mask></defs>
  <g mask="url(#m)" fill="none" stroke="#000" stroke-width="1.85" stroke-linecap="round" stroke-linejoin="round">${BRAIN.map(d => `<path d="${d}"/>`).join('')}</g>
  ${badge}
</svg>`

const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox'] })
const page = await browser.newPage()
const out = {}

for (const [name, badge] of Object.entries(badges)) {
  for (const scale of [1, 2]) {
    const px = 18 * scale
    await page.setContent(`<html><body style="margin:0;background:transparent">${svg(badge, px)}</body></html>`)
    const png = await page.locator('svg').screenshot({ omitBackground: true })
    out[`${name}@${scale}x`] = png.toString('base64')
  }
}

await browser.close()

const target = path.join(path.dirname(new URL(import.meta.url).pathname), '..', 'electron', 'hud-tray-icons.ts')
const body = Object.entries(out)
  .map(([key, value]) => `  '${key}': '${value}'`)
  .join(',\n')

fs.writeFileSync(
  target,
  `// Generated by scripts/gen-hud-tray-icons.mjs — the Brain menu-bar icon (lucide "brain", ISC) as template PNGs.\n` +
    `// Black on transparent: macOS tints a template image for light and dark menu bars.\n\n` +
    `export type HudTrayIcon = 'done' | 'idle' | 'waiting' | 'working1' | 'working2' | 'working3'\n\n` +
    `export const HUD_TRAY_ICONS: Record<\`\${HudTrayIcon}@\${1 | 2}x\`, string> = {\n${body}\n}\n`
)
console.log('wrote', target)
